import assert from "node:assert/strict"
import { existsSync, mkdirSync, realpathSync, writeFileSync } from "node:fs"
import { tmpdir } from "node:os"
import { join } from "node:path"
import { chromium } from "playwright-core"
import { createServer } from "vite"
import { resources } from "../src/lib/i18n/resources.ts"
import { installShellFixture } from "./shell-performance-fixture.mjs"

const executablePath = [process.env.CHROME_PATH, "/Applications/Google Chrome.app/Contents/MacOS/Google Chrome", "/usr/bin/google-chrome", "/usr/bin/chromium"].find(path => path && existsSync(path))
assert.ok(executablePath, "Chrome required")
const output = process.env.INEFFABLE_COMPOSER_SETTINGS_OUTPUT || join(tmpdir(), "ineffable-composer-settings")
mkdirSync(output, { recursive: true })
const results = []
const shellOnly = process.argv.includes("--shell-only")
const server = await createServer({ root: process.cwd(), logLevel: "error", server: { host: "127.0.0.1", port: 0, watch: null, hmr: false, fs: { allow: [process.cwd(), realpathSync("node_modules")] } } })
let browser
try {
  await server.listen()
  browser = await chromium.launch({ executablePath, headless: true })
  for (const language of shellOnly ? [] : ["zh-CN", "en-US"]) for (const theme of ["light", "dark"]) for (const width of [300, 320, 390, 768]) {
    const t = resources[language].translation
    const page = await browser.newPage({ viewport: { width, height: 900 }, locale: language, hasTouch: width <= 390 })
    const errors = []
    page.on("pageerror", error => errors.push(error.message))
    await page.goto(`http://127.0.0.1:${server.httpServer.address().port}/scripts/composer-settings-fixture.html?${new URLSearchParams({ width: String(width), lang: language, theme })}`)
    const input = page.getByRole("textbox", { name: t.chat.composer.messageLabel, exact: true })
    const model = page.getByRole("button", { name: new RegExp(`^${t.chat.composer.modelPickerLabel}:`) })
    const settings = page.getByRole("button", { name: t.chat.composer.runSettings, exact: true })
    const dialog = page.getByRole("dialog", { name: t.chat.composer.runSettings, exact: true })
    const send = page.getByRole("button", { name: t.chat.composer.send, exact: true })
    await model.waitFor()
    assert.equal(await send.isDisabled(), true)
    assert.equal(await model.isEnabled(), true)
    assert.equal(await settings.isEnabled(), true)
    const opacity = await input.evaluate(node => getComputedStyle(node.closest('[data-slot="input-group"]')).opacity)
    assert.equal(opacity, "1", "a disabled Send must not dim the composer")
    assert.equal(await page.locator("[data-disabled-control-fixture]").evaluate(node => getComputedStyle(node).opacity), "0.5", "an actually disabled input keeps its disabled group treatment")
    const geometry = await page.locator("[data-composer-fixture]").evaluate(node => {
      const row = node.querySelector("[data-composer-primary-actions]").getBoundingClientRect()
      const bounds = node.getBoundingClientRect()
      return { overflow: node.scrollWidth - node.clientWidth, width: bounds.width, rowWidth: row.width, buttons: [...node.querySelectorAll("[data-composer-primary-actions] button")].map(button => { const r = button.getBoundingClientRect(); return { left: r.left, right: r.right, width: r.width } }) }
    })
    assert.ok(geometry.overflow <= 1, `composer overflow: ${JSON.stringify(geometry)}`)
    assert.ok(geometry.buttons.every(button => button.left >= -1 && button.right <= width + 1 && button.width >= 24), "primary actions stay visible and usable")
    const modelLabel = await model.locator("span").last().evaluate(node => ({ height: node.getBoundingClientRect().height, horizontalOverflow: node.scrollWidth - node.clientWidth }))
    if (width <= 390) assert.ok(modelLabel.height >= 30, "narrow model trigger uses two readable lines")
    assert.ok(modelLabel.horizontalOverflow <= 1, "model label wraps within its available width")
    await page.screenshot({ path: join(output, `${language}-${theme}-${width}-composer.png`), fullPage: true })
    await input.fill("KEEP_MY_DRAFT")
    if (width <= 390) await settings.tap()
    else { await settings.focus(); await page.keyboard.press("Enter") }
    await dialog.waitFor()
    const settingsGeometry = await dialog.evaluate(node => {
      const rect = node.getBoundingClientRect()
      return { left: rect.left, right: rect.right, overflow: node.scrollWidth - node.clientWidth, fields: [...node.querySelectorAll('[data-slot="field"],label')].map(field => field.scrollWidth - field.clientWidth) }
    })
    assert.ok(settingsGeometry.left >= -1 && settingsGeometry.right <= width + 1 && settingsGeometry.overflow <= 1 && settingsGeometry.fields.every(overflow => overflow <= 1), `settings fit viewport: ${JSON.stringify(settingsGeometry)}`)
    const sandbox = page.getByRole("button", { name: new RegExp(`^${t.chat.composer.sandboxPickerLabel}:`) })
    await sandbox.focus(); await page.keyboard.press("Enter")
    await page.getByRole("option", { name: /Remote B/ }).click()
    assert.equal(await dialog.isVisible(), true, "nested sandbox selection keeps settings open")
    await sandbox.filter({ hasText: "Remote B" }).waitFor()
    const capability = page.getByRole("button", { name: new RegExp(`^${t.chat.composer.capabilityModeLabel}:`) })
    await capability.click()
    await page.getByRole("menuitemradio", { name: t.chat.composer.capabilityMode.full, exact: true }).click()
    await capability.filter({ hasText: t.chat.composer.capabilityMode.full }).waitFor()
    assert.equal(await dialog.isVisible(), true, "nested capability selection keeps settings open")
    const iteration = page.getByRole("switch", { name: new RegExp(`^${t.chat.composer.nodeIteration}`) })
    if (width <= 390) await iteration.tap(); else await iteration.click()
    assert.equal(await iteration.isChecked(), true)
    await sandbox.click()
    await page.getByRole("listbox").waitFor()
    await page.keyboard.press("Escape")
    await page.getByRole("listbox").waitFor({ state: "hidden" })
    assert.equal(await dialog.isVisible(), true)
    assert.equal(await sandbox.evaluate(node => node === document.activeElement), true, "nested Escape restores focus to its trigger")
    if (language === "en-US" && theme === "light" && width === 390) {
      await page.evaluate(() => { window.composerSettingsFixture.setSandboxError("Environment directory is temporarily unavailable"); window.composerSettingsFixture.setSandboxLoading(true) })
      await sandbox.click()
      const alert = page.getByRole("alert").filter({ hasText: "Environment directory is temporarily unavailable" })
      await alert.waitFor()
      assert.equal(await alert.getByRole("button", { name: t.common.retry, exact: true }).isDisabled(), true)
      await page.evaluate(() => window.composerSettingsFixture.setSandboxLoading(false))
      const before = await page.evaluate(() => window.composerSettingsFixture.snapshot().calls.filter(call => call.action === "sandbox-refresh").length)
      await alert.getByRole("button", { name: t.common.retry, exact: true }).click()
      assert.equal(await page.evaluate(() => window.composerSettingsFixture.snapshot().calls.filter(call => call.action === "sandbox-refresh").length), before + 1)
      await page.evaluate(() => window.composerSettingsFixture.setSandboxError(null))
      await alert.waitFor({ state: "hidden" })
      await page.keyboard.press("Escape")
      await page.getByRole("listbox").waitFor({ state: "hidden" })
    }
    await page.screenshot({ path: join(output, `${language}-${theme}-${width}.png`), fullPage: true })
    await page.keyboard.press("Escape")
    await dialog.waitFor({ state: "hidden" })
    assert.equal(await settings.evaluate(node => node === document.activeElement), true, "settings Escape restores trigger focus")
    assert.equal(await input.inputValue(), "KEEP_MY_DRAFT")
    await send.click()
    let snapshot = await page.evaluate(() => window.composerSettingsFixture.snapshot())
    assert.equal(snapshot.calls.filter(call => call.action === "send").length, 1)
    assert.equal(snapshot.calls.find(call => call.action === "send").value.sandbox, "b")
    assert.equal(snapshot.calls.find(call => call.action === "send").value.selection.mode, "full")
    assert.equal(snapshot.calls.find(call => call.action === "send").value.iteration, true)
    await page.evaluate(() => window.composerSettingsFixture.setLive(true))
    await page.getByRole("button", { name: t.chat.composer.stop, exact: true }).click()
    await settings.click()
    await dialog.waitFor()
    await page.evaluate(() => window.composerSettingsFixture.setScope("conversation-b"))
    await dialog.waitFor({ state: "hidden" })
    await settings.click()
    await sandbox.filter({ hasText: "Remote B" }).waitFor()
    assert.equal(await iteration.isChecked(), true, "closing settings never resets canonical selection")
    snapshot = await page.evaluate(() => window.composerSettingsFixture.snapshot())
    assert.equal(snapshot.calls.filter(call => call.action === "stop").length, 1)
    assert.equal(snapshot.composer, "KEEP_MY_DRAFT")
    assert.deepEqual(errors, [])
    results.push({ language, theme, width, opacity, geometry, settingsGeometry, modelLabel, passed: true })
    console.log(`composer settings: ${language}/${theme}/${width}px passed`)
    await page.close()
  }
  // Exercise the same nested portals inside the real modal mobile Sidebar Sheet.
  for (const width of [390, 900]) {
    const page = await browser.newPage({ viewport: { width, height: 900 }, locale: "en-US", hasTouch: true })
    const fixture = await installShellFixture(page, false)
    const policy = { allowed_modes: ["smart", "clean", "full", "custom"], exposure_budget: { max_count: 12 } }
    let policyReads = 0
    await page.route("**/gateway/v1/conversations/capability-exposure/policy*", route => { policyReads++; return route.fulfill({ json: { selection: { mode: "smart" }, capability_exposure_policy: { policy } } }) })
    await page.route("**/gateway/v1/sandbox/environments*", route => route.fulfill({ json: { providers: [{ provider_id: "remote-a", display_name: "Remote A", status: "online" }, { provider_id: "remote-b", display_name: "Remote B", status: "online" }], environments: [{ environment_id: "a", provider_id: "remote-a", status: "ready" }, { environment_id: "b", provider_id: "remote-b", status: "ready" }] } }))
    await page.goto(`http://127.0.0.1:${server.httpServer.address().port}/channels`)
    await page.getByRole("button", { name: "Open AI assistant", exact: true }).click()
    const sheet = page.getByRole("dialog", { name: "Sidebar", exact: true })
    const input = page.getByRole("textbox", { name: "Conversation message", exact: true })
    await sheet.waitFor()
    const backgroundButton = page.locator('header button[aria-label="Close AI assistant"]').first()
    await page.waitForFunction(() => Boolean(document.querySelector('header button[aria-label="Close AI assistant"]')?.closest('[aria-hidden="true"]')))
    assert.equal(await backgroundButton.evaluate(node => Boolean(node.closest('[aria-hidden="true"]'))), true, "the modal Sheet hides background controls from the accessibility tree")
    await backgroundButton.evaluate(node => node.focus())
    assert.equal(await sheet.evaluate(node => node.contains(document.activeElement)), true, "the modal Sheet prevents background focus")
    await input.fill("KEEP_REAL_SHEET_DRAFT")
    const settings = page.getByRole("button", { name: "Run settings", exact: true })
    const dialog = page.getByRole("dialog", { name: "Run settings", exact: true })
    await settings.tap()
    await dialog.waitFor()
    const sandbox = page.getByRole("button", { name: /^Choose a Sandbox environment:/ })
    await sandbox.tap()
    await page.getByRole("option", { name: /Remote B/ }).tap()
    await sandbox.filter({ hasText: "Remote B" }).waitFor()
    assert.equal(await dialog.isVisible(), true)
    assert.equal(await sheet.isVisible(), true, "sandbox portal interaction stays inside the parent Sheet")
    const capability = page.getByRole("button", { name: /^Capability exposure:/ })
    await capability.tap()
    assert.ok(policyReads > 0, "the real draft policy request uses the configured test policy")
    await page.getByRole("menuitemradio", { name: "All tools", exact: true }).tap()
    await capability.filter({ hasText: "All tools" }).waitFor()
    assert.equal(await dialog.isVisible(), true)
    assert.equal(await sheet.isVisible(), true, "capability portal interaction stays inside the parent Sheet")
    await sandbox.tap()
    await page.getByRole("listbox").waitFor()
    await page.keyboard.press("Escape")
    await page.getByRole("listbox").waitFor({ state: "hidden" })
    assert.equal(await dialog.isVisible(), true)
    assert.equal(await sheet.isVisible(), true)
    assert.equal(await sandbox.evaluate(node => document.activeElement === node), true)
    await page.screenshot({ path: join(output, `actual-shell-${width}-settings.png`), fullPage: true })
    await page.keyboard.press("Escape")
    await dialog.waitFor({ state: "hidden" })
    assert.equal(await sheet.isVisible(), true, "the second Escape closes only the settings layer")
    assert.equal(await settings.evaluate(node => document.activeElement === node), true)
    await settings.tap()
    await dialog.waitFor()
    const popoverBounds = await dialog.boundingBox()
    assert.ok(popoverBounds && !(width - 16 >= popoverBounds.x && width - 16 <= popoverBounds.x + popoverBounds.width && 100 >= popoverBounds.y && 100 <= popoverBounds.y + popoverBounds.height), "outside tap point is clear of the settings surface")
    await sheet.tap({ position: { x: width - 16, y: 100 } })
    await dialog.waitFor({ state: "hidden" })
    assert.equal(await sheet.isVisible(), true, "outside settings interaction inside the Sheet does not close the Sheet")
    assert.equal(await input.inputValue(), "KEEP_REAL_SHEET_DRAFT")
    await page.keyboard.press("Escape")
    await sheet.waitFor({ state: "hidden" })
    await page.getByRole("button", { name: "Open AI assistant", exact: true }).click()
    await sheet.waitFor()
    assert.equal(await input.inputValue(), "KEEP_REAL_SHEET_DRAFT", "closing and reopening the real Sheet retains the draft")
    await settings.tap()
    await sandbox.filter({ hasText: "Remote B" }).waitFor()
    await capability.filter({ hasText: "All tools" }).waitFor()
    assert.deepEqual(fixture.errors, [])
    assert.deepEqual(fixture.unexpected, [])
    results.push({ kind: "actual-shell", width, passed: true })
    console.log(`composer settings: actual mobile Sheet/${width}px nested portals and draft passed`)
    await page.close()
  }
  // Preserve the real Composer while temporary portals close at each dock/Sheet
  // transition. Reopen each surface on both sides to exercise stack ownership.
  for (const width of [320, 900]) for (const variant of ["settings", "sandbox", "capability", "model", "history", "attachments"]) {
    const page = await browser.newPage({ viewport: { width, height: 900 }, locale: "en-US", hasTouch: true })
    const fixture = await installShellFixture(page, false, { leftOpen: false })
    const policy = { allowed_modes: ["smart", "full"], exposure_budget: { max_count: 12 } }
    await page.route("**/gateway/v1/conversations/capability-exposure/policy*", route => route.fulfill({ json: { selection: { mode: "smart" }, capability_exposure_policy: { policy } } }))
    await page.route("**/gateway/v1/sandbox/environments*", route => route.fulfill({ json: { providers: [{ provider_id: "remote-b", display_name: "Remote B", status: "online" }], environments: [{ environment_id: "b", provider_id: "remote-b", status: "ready" }] } }))
    await page.goto(`http://127.0.0.1:${server.httpServer.address().port}/channels`)
    const opener = page.getByRole("button", { name: "Open AI assistant", exact: true })
    await opener.click()
    const sheet = page.getByRole("dialog", { name: "Sidebar", exact: true })
    const input = page.getByRole("textbox", { name: "Conversation message", exact: true })
    const settings = page.getByRole("button", { name: "Run settings", exact: true })
    const settingsDialog = page.getByRole("dialog", { name: "Run settings", exact: true })
    const sandbox = page.getByRole("button", { name: /^Choose a Sandbox environment:/ })
    const capability = page.getByRole("button", { name: /^Capability exposure:/ })
    const model = page.getByRole("button", { name: /^Choose a model:/ })
    const history = page.locator('[data-slot="sidebar-header"] [data-slot="dropdown-menu-trigger"]').last()
    const attachments = page.getByRole("button", { name: "Add images", exact: true })
    const temporaryLayers = page.locator('[data-slot="popover-content"], [data-slot="dropdown-menu-content"]')
    await input.fill("KEEP_RESIZE_DRAFT")
    const originalInput = await input.elementHandle()
    await model.tap()
    await page.getByRole("option", { name: /Fixture model/ }).tap()
    await settings.tap()
    await sandbox.tap()
    await page.getByRole("option", { name: /Remote B/ }).tap()
    await capability.tap()
    await page.getByRole("menuitemradio", { name: "All tools", exact: true }).tap()
    await page.getByRole("menu").waitFor({ state: "hidden" })
    await page.keyboard.press("Escape")
    await settingsDialog.waitFor({ state: "hidden" })

    const nested = variant === "sandbox" || variant === "capability"
    const trigger = variant === "model" ? model : variant === "history" ? history : variant === "attachments" ? attachments : settings
    const deepestTrigger = variant === "sandbox" ? sandbox : variant === "capability" ? capability : trigger
    const layer = variant === "sandbox" || variant === "model"
      ? page.locator('[data-slot="popover-content"]').filter({ has: page.getByRole("listbox") })
      : variant === "capability" || variant === "history" || variant === "attachments"
        ? page.getByRole("menu")
        : settingsDialog

    async function openLayer() {
      await trigger.tap()
      if (nested) await deepestTrigger.tap()
      await layer.waitFor()
      await layer.evaluate(async node => { await Promise.allSettled(node.getAnimations().map(animation => animation.finished)) })
      assert.equal(await layer.evaluate(node => Boolean(node.closest('[aria-hidden="true"]'))), false, "the top temporary surface stays in the accessibility tree")
      const hit = await layer.evaluate(node => {
        const rect = node.getBoundingClientRect()
        return node.contains(document.elementFromPoint(rect.x + rect.width / 2, rect.y + rect.height / 2))
      })
      assert.equal(hit, true, "the top temporary surface is above the parent Sheet")
    }

    async function assertPreserved() {
      assert.equal(await input.evaluate((node, original) => node === original, originalInput), true, "presentation changes retain the same Composer input DOM instance")
      assert.equal(await input.count(), 1, "there is only one Composer input")
      assert.equal(await input.inputValue(), "KEEP_RESIZE_DRAFT")
      assert.equal(await page.evaluate(() => localStorage.getItem("ineffable.ui.right-sidebar.open")), "true", "a presentation change does not close chat")
      await model.filter({ hasText: "Fixture model" }).waitFor()
    }

    await openLayer()
    await page.setViewportSize({ width: 1200, height: 900 })
    await sheet.waitFor({ state: "hidden" })
    await page.waitForFunction(() => !document.querySelector('[data-slot="popover-content"], [data-slot="dropdown-menu-content"]'))
    await assertPreserved()
    assert.equal(await trigger.evaluate(node => document.activeElement === node), true, "leaving the Sheet returns focus to the temporary layer trigger")
    await openLayer()
    await page.setViewportSize({ width, height: 900 })
    await sheet.waitFor()
    await page.waitForFunction(() => !document.querySelector('[data-slot="popover-content"], [data-slot="dropdown-menu-content"]'))
    await assertPreserved()
    assert.equal(await trigger.evaluate(node => document.activeElement === node), true, "entering the Sheet restores focus to the temporary layer trigger")
    const background = page.locator('header button[aria-label="Close AI assistant"]').first()
    assert.equal(await background.evaluate(node => Boolean(node.closest('[aria-hidden="true"]'))), true, "the new Sheet retains background aria isolation")
    await background.evaluate(node => node.focus())
    assert.equal(await sheet.evaluate(node => node.contains(document.activeElement)), true, "the new Sheet retains focus containment")
    await page.screenshot({ path: join(output, `actual-shell-resize-${width}-${variant}-returned.png`), fullPage: true })

    await openLayer()
    await page.screenshot({ path: join(output, `actual-shell-resize-${width}-${variant}-reopened.png`), fullPage: true })
    await page.keyboard.press("Escape")
    await layer.waitFor({ state: "hidden" })
    assert.equal(await sheet.isVisible(), true, "Escape closes the top temporary surface before the Sheet")
    assert.equal(await deepestTrigger.evaluate(node => document.activeElement === node), true, "Escape returns focus to the immediate trigger")
    if (nested) {
      assert.equal(await settingsDialog.isVisible(), true, "nested Escape retains the settings surface")
      await page.keyboard.press("Escape")
      await settingsDialog.waitFor({ state: "hidden" })
      assert.equal(await settings.evaluate(node => document.activeElement === node), true)
      assert.equal(await sheet.isVisible(), true)
    }
    await page.keyboard.press("Escape")
    await sheet.waitFor({ state: "hidden" })
    assert.equal(await temporaryLayers.count(), 0, "closing chat leaves no orphan temporary portals")
    await opener.click()
    await sheet.waitFor()
    await assertPreserved()
    await settings.tap()
    await sandbox.filter({ hasText: "Remote B" }).waitFor()
    await capability.filter({ hasText: "All tools" }).waitFor()
    assert.deepEqual(fixture.errors, [])
    assert.deepEqual(fixture.unexpected, [])
    results.push({ kind: "actual-shell-resize", width, variant, passed: true })
    console.log(`composer settings: actual Sheet/${width}px dock round trip/${variant} passed`)
    await originalInput.dispose()
    await page.close()
  }
  writeFileSync(join(output, "results.json"), JSON.stringify(results, null, 2))
} finally {
  await browser?.close()
  await server.close()
}
